local T = import("test/environment.lua")
local Color = import("goluwa/structs/color.lua")
local Vec3 = import("goluwa/structs/vec3.lua")

T.Test("Set assigns every field and returns the struct, including a field named a", function()
	local color = Color(0, 0, 0, 0)
	T(color:Set(0.25, 0.5, 0.75, 1))["=="](color)
	T(color.r)["=="](0.25)
	T(color.g)["=="](0.5)
	T(color.b)["=="](0.75)
	T(color.a)["=="](1)
	local vec = Vec3()
	T(vec:Set(1, 2, 3))["=="](vec)
	T(vec.z)["=="](3)
end)
