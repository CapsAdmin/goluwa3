T.Test("Buffer ReadVariableSizedInteger", function()
	local buf = ffi.new("uint8_t[10]")
	local buffer = Buffer.New(buf, 10):MakeWritable()
	buffer:WriteByte(0xAB)
	buffer:WriteByte(0x01)
	buffer:SetPosition(0)
	T(buffer:ReadVariableSizedInteger(2))["=="](171)
end)

