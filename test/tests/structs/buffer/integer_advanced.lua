local T = import("test/environment.lua")
local ffi = require("ffi")
local Buffer = import("goluwa/structs/buffer.lua")

T.Test("Buffer WritePackedInteger ReadPackedInteger", function()
	local buf = ffi.new("uint8_t[10]")
	local buffer = Buffer.New(buf, 10)
	buffer:WritePackedInteger(0x12345678, 4, false)
	buffer:SetPosition(0)
	T(buffer:ReadPackedInteger(4, false))["=="](0x12345678)
end)

T.Test("Buffer WritePackedInteger ReadPackedInteger signed -1", function()
	local buf = ffi.new("uint8_t[10]")
