local T = import("test/environment.lua")
local exposure = import("goluwa/render3d/exposure.lua")

local function reset()
	for _, info in ipairs(exposure.fields) do
		exposure.Set(info.key, info.default)
	end
end

T.Test("Graphics render3d exposure clamps numbers and refuses what it doesn't know", function()
	exposure.Set("camera.grey", 500)
	T(exposure.Get("camera.grey"))["=="](90)
	T(pcall(exposure.Set, "camera.mode", "sideways"))["=="](false)
	T(pcall(exposure.Set, "camera.grey", "bright"))["=="](false)
	T(pcall(exposure.Get, "camera.nothing"))["=="](false)
	reset()
end)

T.Test("Graphics render3d exposure the grey midpoint is the compensation in stops", function()
	exposure.Set("camera.grey", 18)
	T(exposure.GetCompensation())["~"](0, 1e-9)
	exposure.Set("camera.grey", 36)
	T(exposure.GetCompensation())["~"](1, 1e-9)
	exposure.Set("eye.enabled", true)
	T(exposure.GetCompensation())["=="](0)
	reset()
end)

T.Test("Graphics render3d exposure the range follows the camera and the eye", function()
	exposure.Set("camera.ev_min", 8)
	exposure.Set("camera.ev_max", 3)
	local lo, hi = exposure.GetRange()
	T(lo)["=="](8)
	T(hi)["=="](8)
	exposure.Set("eye.enabled", true)
	lo, hi = exposure.GetRange()
	exposure.Set("eye.adaptation_min", 0)
	exposure.Set("eye.adaptation_max", 2)
	lo, hi = exposure.GetRange()
	T(lo)["=="](3)
	T(hi)["~"](3 + 2 * math.log(10) / math.log(2), 1e-9)
	reset()
end)

T.Test("Graphics render3d exposure only manual mode locks the exposure", function()
	T(exposure.GetManualEV())["=="](nil)
	exposure.Set("camera.mode", "manual")
	exposure.Set("camera.iso", 100)
	exposure.Set("camera.aperture", 8)
	exposure.Set("camera.shutter", 1 / 64)
	T(exposure.GetManualEV())["~"](12, 1e-9)
	exposure.Set("camera.iso", 400)
	T(exposure.GetManualEV())["~"](10, 1e-9)
	reset()
end)
