local T = import("test/environment.lua")
local sprites = import("goluwa/render3d/sprites.lua")
local event = import("goluwa/event.lua")

T.Test3D("A sprite batch keeps its world bounds on the sprites that moved", function()
	local batch = sprites.GetBatch(nil, {Additive = true, IgnoreZ = true})

	for i = 1, 3 do
		batch:Add(i * 10, 1, 0, 0.05, 1, 1, 1, 1)
		event.Call("LateUpdate")
		local bounds = batch.entity.visual:GetWorldAABB()
		T(bounds.min_x)["<="](i * 10)
		T(bounds.max_x)[">="](i * 10)
		T(bounds.max_x - bounds.min_x)["<"](1)
	end

	event.Call("LateUpdate")
	batch.entity:Remove()
end)

T.Test3D("A sprite takes its uv from the atlas frame", function()
	local vertex_layout = import("goluwa/render3d/vertex_layout.lua")
	local uv = vertex_layout.GetFloatOffset("uv")
	local stride = vertex_layout.FloatStride
	local batch = sprites.GetBatch(nil, {Additive = true, IgnoreZ = true})
	batch:SetAtlas(4, 2)
	batch:Add(0, 1, 0, 0.5, 1, 1, 1, 1, 6, 0.5)
	batch:Add(0, 1, 0, 0.5, 1, 1, 1, 1)
	local floats = batch.floats
	T(floats[uv])["=="](0.5)
	T(floats[uv + 1])["=="](0.5)
	T(floats[2 * stride + uv])["=="](0.75)
	T(floats[2 * stride + uv + 1])["=="](1)
	T(floats[4 * stride + uv])["=="](0)
	T(floats[6 * stride + uv + 1])["=="](1)
	event.Call("LateUpdate")
	event.Call("LateUpdate")
	batch.entity:Remove()
end)

T.Test3D("A near fading sprite disappears around the camera", function()
	local render3d = import("goluwa/render3d/render3d.lua")
	local camera = render3d.GetCamera():GetPosition()
	local batch = sprites.GetBatch(nil, {Additive = true, IgnoreZ = true})
	batch:SetNearFade(0.5, 1.5)
	batch:Add(camera.x, camera.y, camera.z, 1, 1, 1, 1, 1)
	T(batch.count)["=="](0)
	batch:Add(camera.x + 10, camera.y, camera.z, 1, 1, 1, 1, 1)
	T(batch.count)["=="](1)
	event.Call("LateUpdate")
	event.Call("LateUpdate")
	batch.entity:Remove()
end)
