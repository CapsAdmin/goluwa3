local T = import("test/environment.lua")
local Material = import("goluwa/render3d/material.lua")
local render3d = import("goluwa/render3d/render3d.lua")
local model_pipeline = import("goluwa/render3d/model_pipeline.lua")

T.Test3D("model_pipeline upload keys follow the material as its properties change", function()
	local material = Material.New()
	render3d.SetMaterial(material)
	local factor_default = model_pipeline.GetPBRFactorUploadKey()
	local aux_default = model_pipeline.GetPBRAuxUploadKey()
	T(factor_default ~= material)["=="](true)
	T(aux_default ~= material)["=="](true)
	T(model_pipeline.GetPBRFactorUploadKey())["=="](factor_default)
	material:SetRoughnessMultiplier(0.5)
	T(model_pipeline.GetPBRFactorUploadKey())["=="](material)
	T(model_pipeline.GetPBRAuxUploadKey())["=="](aux_default)
	material:SetRoughnessMultiplier(1)
	T(model_pipeline.GetPBRFactorUploadKey())["=="](factor_default)
	material:SetAmbientOcclusionMultiplier(0.5)
	T(model_pipeline.GetPBRAuxUploadKey())["=="](material)
	material:SetAmbientOcclusionMultiplier(1)
	material:SetAdditive(true)
	T(model_pipeline.GetPBRAuxUploadKey())["=="](material)
	material:SetAdditive(false)
	T(model_pipeline.GetPBRAuxUploadKey())["=="](aux_default)
	-- params of the features that are in the factor block count too
	material:SetClearcoat(0.5)
	T(model_pipeline.GetPBRFactorUploadKey())["=="](material)
	material:SetClearcoat(0)
	T(model_pipeline.GetPBRFactorUploadKey())["=="](factor_default)
	render3d.SetMaterial(nil)
end)
