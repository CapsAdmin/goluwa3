local T = import("test/environment.lua")
local Entity = import("goluwa/entities/entity.lua")
local Vec3 = import("goluwa/structs/vec3.lua")
local BoxShape = import("goluwa/physics/shapes/box.lua")

local function spawn_body()
	local ent = Entity.New({Name = "force_target"})
	ent:AddComponent("transform")
	ent.transform:SetPosition(Vec3(0, 0, 0))
	local body = ent:AddComponent("rigid_body", {Shape = BoxShape.New(Vec3(1, 1, 1)), GravityScale = 0, CanSleep = false})
	return ent, body
end

T.TestPhysics("ApplyForceAt accumulates the same force and torque as ApplyForce", function()
	local ent_a, a = spawn_body()
	local ent_b, b = spawn_body()
	local force, point = Vec3(3, -2, 5), Vec3(0.5, 1, -0.25)
	a:ApplyForce(force, point)
	b:ApplyForceAt(force.x, force.y, force.z, point.x, point.y, point.z)
	local fa, fb = a:GetAccumulatedForce(), b:GetAccumulatedForce()
	local ta, tb = a:GetAccumulatedTorque(), b:GetAccumulatedTorque()
	T(fb.x)["~"](fa.x)
	T(fb.y)["~"](fa.y)
	T(fb.z)["~"](fa.z)
	T(tb.x)["~"](ta.x)
	T(tb.y)["~"](ta.y)
	T(tb.z)["~"](ta.z)
	ent_a:Remove()
	ent_b:Remove()
end)

T.TestPhysics("ApplyForceAt pushes a body and spins it when the point is off the center", function()
	local ent, body = spawn_body()
	body:ApplyForceAt(0, 0, 100, 1, 0, 0)
	import("goluwa/physics.lua").Update(1 / 60)
	T(body:GetVelocity().z)[">"](0)
	T(math.abs(body:GetAngularVelocity().y))[">"](0)
	ent:Remove()
end)
