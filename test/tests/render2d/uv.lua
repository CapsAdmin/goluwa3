T.Test2D("Graphics render2d SetSDFUV does not affect GetUV state", function()
	render2d.SetSDFScaledUVFlippedY(50, 60, 70, 80, 256, 256)
	local x, y = render2d.GetSDFScaledUVFlippedY()
	T(x)["=="](50)
	T(y)["=="](60)
	-- SetSDFUV only changes fragment constants, not the uv state object
	render2d.SetSDFUV(0.5, 0.5, 1.0, 1.0)
	x, y = render2d.GetSDFScaledUVFlippedY()
	T(x)["=="](50)
	T(y)["=="](60)
end)

T.Test2D("Graphics render2d PushUV PopUV preserves transform state", function()
	render2d.SetSDFScaledUVFlippedY(10, 20, 30, 40, 100, 100)
	render2d.PushSDFScaledUVFlippedY(50, 60, 70, 80, 200, 200)
	-- After push, both GetUV and GetSDFUVTransformed should reflect pushed state
	local x, y = render2d.GetSDFScaledUVFlippedY()
	T(x)["=="](50)
	T(y)["=="](60)
	local off_x, off_y, scale_x, scale_y = render2d.GetSDFUVTransformed()
	T(off_x)["~"](50 / 200)
	T(off_y)["~"]((-60 - 80) / 200)
	render2d.PopSDFScaledUVFlippedY()
	-- After pop, should restore original state
	x, y = render2d.GetSDFScaledUVFlippedY()
	T(x)["=="](10)
	T(y)["=="](20)
	off_x, off_y, scale_x, scale_y = render2d.GetSDFUVTransformed()
	T(off_x)["~"](10 / 100)
	T(off_y)["~"]((-20 - 40) / 100)
end)

T.Test2D("Graphics render2d PushUV PopUV after SetSDFUV preserves SetUV state", function()
	-- SetSDFUV only changes fragment constants, not the uv state object
	render2d.SetSDFScaledUVFlippedY(10, 20, 30, 40, 100, 100)
	render2d.SetSDFUV(0.1, 0.2, 0.9, 0.8) -- changes constants but not uv state
	-- PushUV saves the uv state (from SetUV), not the constants
	render2d.PushSDFScaledUVFlippedY(50, 60, 70, 80, 200, 200)
	local x, y = render2d.GetSDFScaledUVFlippedY()
	T(x)["=="](50)
	T(y)["=="](60)
	render2d.PopSDFScaledUVFlippedY()
	-- After pop, uv state should be restored to SetUV values (not SetSDFUV)
	x, y = render2d.GetSDFScaledUVFlippedY()
	T(x)["=="](10)
	T(y)["=="](20)
	-- But GetSDFUVTransformed should reflect the SetUV transform, not SetSDFUV
	local off_x, off_y, scale_x, scale_y = render2d.GetSDFUVTransformed()
	T(off_x)["~"](10 / 100)
	T(off_y)["~"]((-20 - 40) / 100)
end)

T.Test2D("Graphics render2d PushUV no args resets to default", function()
	render2d.SetSDFScaledUVFlippedY(10, 20, 30, 40, 100, 100)
	-- PushSDFScaledUVFlippedY() with no args: saves current state, calls SetUV(nil) which resets
	render2d.PushSDFScaledUVFlippedY()
	local x = render2d.GetSDFScaledUVFlippedY()
	T(x)["=="](nil) -- reset returns nil for x
	render2d.PopSDFScaledUVFlippedY()
	x = render2d.GetSDFScaledUVFlippedY()
	T(x)["=="](10)
end)

