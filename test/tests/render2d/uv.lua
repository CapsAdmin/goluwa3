T.Test2D("Graphics render2d SetUV transform constants are correct", function()
	-- UV offset/scale should be computed from pixel coords divided by scale
	render2d.SetSDFScaledUVFlippedY(100, 200, 50, 100, 1024, 1024)
	local off_x, off_y, scale_x, scale_y = render2d.GetSDFUVTransformed()
	T(off_x)["~"](100 / 1024)
	T(off_y)["~"]((-200 - 100) / 1024) -- y_transformed = -y - h
	T(scale_x)["~"](50 / 1024)
	T(scale_y)["~"](100 / 1024)
end)

T.Test2D("Graphics render2d SetSDFUV GetSDFUVTransformed", function()
