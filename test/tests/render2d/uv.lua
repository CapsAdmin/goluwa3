T.Test2D("Graphics render2d SetUV is idempotent - GetUV returns original params", function()
	-- SetUV must store original parameters, not transformed ones
	render2d.SetSDFScaledUVFlippedY(10, 20, 100, 200, 512, 512)
	local x, y, w, h, sx, sy = render2d.GetSDFScaledUVFlippedY()
	T(x)["=="](10)
	T(y)["=="](20)
	T(w)["=="](100)
	T(h)["=="](200)
	T(sx)["=="](512)
	T(sy)["=="](512)
	-- GetUV then SetUV with returned values should be idempotent
	render2d.SetSDFScaledUVFlippedY(x, y, w, h, sx, sy)
	x, y, w, h, sx, sy = render2d.GetSDFScaledUVFlippedY()
	T(x)["=="](10)
	T(y)["=="](20)
	T(w)["=="](100)
	T(h)["=="](200)
	T(sx)["=="](512)
	T(sy)["=="](512)
end)

