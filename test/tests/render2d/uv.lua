T.Test2D("Graphics render2d preserves fragment constant values across resolved storage", function()
	render2d.SetSDFUV(0.25, 0.5, 0.75, 1.0)
	render2d.SetSDFSoftness(3)
	render2d.SetBorderRadius(1, 2, 3, 4)
	render2d.SetOutlineWidth(6)
	render2d.SetNinePatch(10, 20, 30, 40, 0)
	render2d.UploadConstants()
	local draw = render2d.pipeline:GetConstantBlockInfo("draw")
	local shape = render2d.pipeline:GetConstantBlockInfo("shape")
	local patch = render2d.pipeline:GetConstantBlockInfo("nine_patch")
	local draw_data = render2d.pipeline:BuildConstantBlockData("draw")
	local shape_data = render2d.pipeline:BuildConstantBlockData("shape")
	local patch_data = render2d.pipeline:BuildConstantBlockData("nine_patch")
	T(draw.storage == "push" or draw.storage == "uniform_buffer")["=="](true)
	T(shape.storage == "push" or shape.storage == "uniform_buffer")["=="](true)
	T(patch.storage == "push" or patch.storage == "uniform_buffer")["=="](true)
	T(draw_data.uv_offset[0])["=="](0.25)
	T(draw_data.uv_offset[1])["=="](0.5)
	T(draw_data.uv_scale[0])["=="](0.5)
	T(draw_data.uv_scale[1])["=="](0.5)
	T(shape_data.border_radius[0])["=="](1)
	T(shape_data.border_radius[1])["=="](2)
	T(shape_data.border_radius[2])["=="](3)
	T(shape_data.border_radius[3])["=="](4)
	T(shape_data.outline_width)["=="](6)
	T(patch_data.nine_patch_x_count)["=="](1)
	T(patch_data.nine_patch_y_count)["=="](1)
	T(patch_data.nine_patch_x_stretch[0])["=="](10)
	T(patch_data.nine_patch_x_stretch[1])["=="](20)
	T(patch_data.nine_patch_y_stretch[0])["=="](30)
	T(patch_data.nine_patch_y_stretch[1])["=="](40)
end)
