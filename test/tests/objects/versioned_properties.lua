local T = import("test/environment.lua")
local objects = import("goluwa/objects/objects.lua")

T.Test("objects versioned properties stamp the object when they change", function()
	local META = objects.CreateTemplate("test_versioned_properties")
	META:StartStorable({versioned = true})
	META:GetSet("Num", 1)
	META:EndStorable()
	META:GetSet("Plain", 1)
	META:Register()
	local obj = objects.CreateObject(META)
	T(obj.property_version)["=="](nil)
	obj:SetNum(2)
	local first = obj.property_version
	T(first ~= nil)["=="](true)
	obj:SetNum(2)
	T(obj.property_version)["=="](first)
	obj:SetNum(3)
	T(obj.property_version > first)["=="](true)
	local second = obj.property_version
	obj:SetPlain(5)
	T(obj.property_version)["=="](second)
	assert(objects.SetProperty(obj, "Num", 10))
	T(obj.property_version > second)["=="](true)
	local other = objects.CreateObject(META)
	other:SetNum(4)
	T(other.property_version ~= obj.property_version)["=="](true)
end)
