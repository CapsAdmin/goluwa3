local T = import("test/environment.lua")
local Entity = import("goluwa/entities/entity.lua")
local Vec3 = import("goluwa/structs/vec3.lua")
local BoxShape = import("goluwa/physics/shapes/box.lua")
local shelter = import("goluwa/shelter.lua")

T.TestPhysics("shelter is high behind a wall and low in front of it, falling with distance", function()
	shelter.Clear()
	local wall = Entity.New({Name = "shelter_wall"})
	wall:AddComponent("transform")
	wall.transform:SetPosition(Vec3(0, 3, 0))
	wall:AddComponent("rigid_body", {Shape = BoxShape.New(Vec3(1, 6, 20)), MotionType = "static"})
	local toward_wall = Vec3(-1, 0, 0)
	local behind = shelter.Get(Vec3(3, 1, 0), toward_wall, 20)
	local in_front = shelter.Get(Vec3(-3, 1, 0), toward_wall, 20)
	local far = shelter.Get(Vec3(17, 1, 0), toward_wall, 20)
	T(behind > 0.6)["=="](true)
	T(in_front < 0.05)["=="](true)
	T(far < behind * 0.3)["=="](true)
	T(shelter.GetAgainst(Vec3(3, 1, 0), Vec3(8, 0, 0), 20))["=="](behind)
	T(shelter.GetAgainst(Vec3(3, 1, 0), Vec3(0, 0, 0), 20))["=="](0)
	wall:Remove()
	shelter.Clear()
end)
