local T = import("test/environment.lua")
local foliage_field = import("goluwa/foliage_field.lua")

T.Test("foliage field covers the cells around an instance near its height", function()
	foliage_field.Clear()
	foliage_field.AddInstance(10, 5, 20, 1)
	T(foliage_field.Sample(10, 6, 20) > 0)["=="](true)
	T(foliage_field.Sample(10, 12, 20))["=="](0)
	T(foliage_field.Sample(40, 6, 20))["=="](0)
	foliage_field.Clear()
	T(foliage_field.Sample(10, 6, 20))["=="](0)
end)

T.Test("foliage field density is the share of the surroundings with canopy or bushes", function()
	foliage_field.Clear()
	T(foliage_field.GetDensity(0, 0, 10))["=="](0)
	foliage_field.AddCanopy(0, 0, 100)
	T(foliage_field.GetDensity(0, 0, 10))["=="](1)
	foliage_field.Clear()
	foliage_field.AddCanopy(0, 0, 3)
	local partial = foliage_field.GetDensity(0, 0, 10)
	T(partial > 0 and partial < 1)["=="](true)
	foliage_field.Clear()
end)
