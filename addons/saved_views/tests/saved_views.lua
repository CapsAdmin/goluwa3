local T = import("test/environment.lua")
local saved_views = import("lua/saved_views.lua")
local weather = import("goluwa/render3d/weather.lua")
local climate = import("goluwa/render3d/climate.lua")
local render3d = import("goluwa/render3d/render3d.lua")
local View = import("goluwa/render3d/view.lua")
local Vec3 = import("goluwa/structs/vec3.lua")
local Quat = import("goluwa/structs/quat.lua")

T.Test3D("saved views store only non default climate and restore the world", function()
	saved_views.SetSceneName("saved_views_test", {A = "1"})
	climate.SetPreset({}, 0)
	T(next(climate.Capture()))["=="](nil)
	weather.SetTime(1795056380)
	weather.SetLocation(-43.5, 106.07)
	climate.SetPreset({rain = 4, wind = Vec3(3, 0, 1), clouds = {{name = "low", coverage = 0.7}}}, 0)
	local view = View.New{
		Priority = 100,
		Position = Vec3(1, 2, 3),
		Rotation = Quat(0, 0.3, 0, 0.9539392):Normalize(),
		FOV = 1.2,
	}:Activate()
	saved_views.Save("test_view", "note")
	view:Remove()
	weather.SetTime(0)
	climate.SetPreset({}, 0)
	local entry = saved_views.Apply("saved_views_test", "test_view")
	local camera = render3d.GetMainCamera()
	saved_views.Release()
	saved_views.Remove("saved_views_test", "test_view")
	T(entry.note)["=="]("note")
	T(entry.args.A)["=="]("1")
	T(weather.GetTime())["=="](1795056380)
	T(weather.GetRain())["=="](4)
	T(weather.GetWind().x)["=="](3)
	T(weather.GetTimeScale())["=="](0)
	T(camera:GetPosition().z)["~"](3, 1e-5)
	T(camera:GetFOV())["~"](1.2, 1e-9)
	T(#weather.GetCloudLayers())["=="](1)
	T(next(climate.Capture()) ~= nil)["=="](true)
	T(pcall(saved_views.Find, "saved_views_test", "test_view"))["=="](false)
end)
